    n = len(s["questions"])
    vmax = max(v for _, v in s["options"])
    vmin = min(v for _, v in s["options"])
    mult = s.get("multiply", 1)
    lo, hi = round(n * vmin * mult), round(n * vmax * mult)
    if hi == lo:
        return 0.0
    x = (score - lo) / (hi - lo)
    if code in POSITIVE_SCALES:
        x = 1 - x
    return round(max(0.0, min(1.0, x)) * 100, 1)



