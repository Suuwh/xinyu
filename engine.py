def assess_scale(code: str, answers: list) -> dict:
    s = SCALES[code]
    vals = [int(x) for x in answers]
    reverse = set(s.get("reverse", []))
    if code == "panas":
        pa_idx = s.get("pa_idx", [])
        na_idx = s.get("na_idx", [])
        pa = sum(vals[i-1] for i in pa_idx)
        na = sum(vals[i-1] for i in na_idx)
        score = pa
        level = "正性情绪高/负性情绪低" if (pa - na) >= 8 else ("情绪平衡" if abs(pa-na) < 8 else "负性情绪偏高")
        return {"score": score, "level": level,"advice": f"正性情绪得分 {pa}，负性情绪得分 {na}。{s['advice']['情绪状态']}","extra": {"pa": pa, "na": na}}
    #反向计分：options最大分值
    vmax = max(v for _, v in s["options"])
    total = 0
    for i, v in enumerate(vals, start=1):
        vmin = min(v for _, v in s["options"])
        total += (vmax + vmin - v) if i in reverse else v
    mult = s.get("multiply", 1)
    score = round(total * mult)
    level = ""
    for lo, hi, name in s["levels"]:
        if lo <= score <= hi:
            level = name; break
    return {"score": score, "level": level, "advice": s["advice"].get(level, "")}


