def assess_scale(code: str, answers: list) -> dict:
    s = SCALES[code]
    vals = [int(x) for x in answers]
    reverse = set(s.get("reverse", []))
    # PANAS 单独处理：分别算正性/负性
    if code == "panas":
        pa_idx = [1, 3, 5, 10, 13, 15, 16, 18, 19, 20]   # 1-based
        na_idx = [2, 4, 6, 7, 8, 9, 11, 12, 14, 17]
        pa = sum(vals[i-1] for i in pa_idx)
        na = sum(vals[i-1] for i in na_idx)
        score = pa
        level = "正性情绪高/负性情绪低" if (pa - na) >= 8 else ("情绪平衡" if abs(pa-na) < 8 else "负性情绪偏高")
        return {"score": score, "level": level,
                "advice": f"正性情绪得分 {pa}，负性情绪得分 {na}。{s['advice']['情绪状态']}",
                "extra": {"pa": pa, "na": na}}
    # 通用反向计分：options最大分值
    vmax = max(v for _, v in s["options"])
    total = 0
    for i, v in enumerate(vals, start=1):
        total += (vmax + (min(v for _, v in s["options"]))) if i in reverse else v
    level = ""
    for lo, hi, name in s["levels"]:
        if lo <= total <= hi:
            level = name; break
    return {"score": total, "level": level, "advice": s["advice"].get(level, "")}
