def detect_emotion(text: str) -> dict:
    risk = "none"
    hits = []
    for w in CRISIS_WORDS:
        if w in text:
            risk = "high"; hits.append(w)
    if risk == "none":
        for emo, words in NEGATIVE.items():
            for w in words:
                if w in text:
                    hits.append(emo); break
        if hits:
            risk = "low"
    emo = hits[0] if hits else "中性"
    score = -1.0 if hits else 0.1
    for p in POSITIVE:
        if p in text:
            emo = "积极"; score = 0.8; break
    return {"emotion": emo, "score": score, "risk": risk, "hits": hits}


def generate_reply(text: str, emotion: dict) -> dict:
    if emotion["risk"] == "high":
        return {"reply": CRISIS_REPLY, "intent": "危机干预",
                "advice": ["立即联系心理中心", "拨打400-161-9995"]}
    best, best_n = None, 0
    for item in KNOWLEDGE:
        n = sum(1 for k in item["keywords"] if k in text)
        if n > best_n:
            best_n = n; best = item
    if best:
        return {"reply": best["reply"], "intent": best["intent"], "advice": best["advice"]}
    return {"reply": random.choice(CLOSE_REPLY), "intent": "倾听陪伴", "advice": []}


