def _params(n_levels, item_idx, reverse=False):
    """根据题目序号伪随机生成稳定的GRM参数。
    n_levels: 可选等级数（5或4）
    reverse: 反向题，阈值整体取反
    """
    # 确定性伪随机（保证题库版本一致）
    seed = (item_idx * 2654435761) % 2**31
    def rnd():
        nonlocal seed
        seed = (seed * 1103515245 + 12345) % 2**31
        return seed / 2**31
    a = 0.9 + rnd() * 1.2                      # 区分度 0.9 ~ 2.1
    n_th = n_levels - 1
    # 阈值在 [-1.6, 1.6] 之间等距基础上加抖动
    centers = [-1.5, -0.5, 0.5, 1.5][:n_th]
    thresholds = [round(c + (rnd() - 0.5) * 0.35, 3) for c in centers]
    thresholds.sort()
    if reverse:
        thresholds = [-t for t in reversed(thresholds)]
    return round(a, 3), thresholds


